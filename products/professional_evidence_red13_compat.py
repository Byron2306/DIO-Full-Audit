def _run_campaign_lab_v2(packet: dict[str, Any], execution_dir: Path) -> dict[str, Any]:
    from adapters.document_studio import local_media_compositor
    from products.professional_evidence_final_compat import _campaign_proof_bridge
    from scripts.build_multichannel_campaign_factory import build_family

    product, audience = _campaign_inputs(packet)
    proof_bridge = _campaign_proof_bridge(packet)
    matrix = json.loads((ROOT / "config" / "marketing_audience_matrix.json").read_text(encoding="utf-8"))
    exact_family = f"{product['id']}--{audience['id']}"
    original_resolver = local_media_compositor.resolve_product_audience

    def resolve_professional_family(family_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
        if family_id == exact_family:
            return product, audience
        return original_resolver(family_id)

    original_gamma = os.environ.get("DIO_GAMMA_VISUAL_CANDIDATE")
    local_media_compositor.resolve_product_audience = resolve_professional_family
    os.environ["DIO_GAMMA_VISUAL_CANDIDATE"] = "0"
    try:
        family = build_family(product, audience, matrix["channels"], execution_dir, True)
    finally:
        local_media_compositor.resolve_product_audience = original_resolver
        if original_gamma is None:
            os.environ.pop("DIO_GAMMA_VISUAL_CANDIDATE", None)
        else:
            os.environ["DIO_GAMMA_VISUAL_CANDIDATE"] = original_gamma

    if (family.get("validation") or {}).get("state") != "passed":
        raise RuntimeError(
            "Campaign Lab did not complete governed media production: "
            + "; ".join((family.get("validation") or {}).get("errors") or [])
        )
    governance = family.get("governance") or {}
    if governance.get("publication") != "held" or governance.get("spend") != "disabled":
        raise RuntimeError("Campaign Lab publication/spend boundary drifted")
    receipt = {
        **family,
        "professional_proof_bridge": str(proof_bridge),
        "customer_packet_fingerprint": packet["packet_fingerprint"],
        "semantic_source_fragments_are_non_cloned": True,
        "gamma_selected_for_professional_gauntlet": False,
        "authority_created": False,
        "external_effects": False,
        "market_validation_claimed": False,
    }
    write_json(execution_dir / "PROFESSIONAL_CAMPAIGN_LAB_RECEIPT.json", receipt)
    return {
        "executor": "LINGUA + Document Studio local compositor + NicheFoundry media",
        "product_id": "campaign_lab",
        "terminal_artifact_kind": "complete_multichannel_campaign",
        "domain_action_executed": False,
        "product_pipeline_executed": True,
        "receipt": receipt,
    }


def _spine_preflight(env: dict[str, str], legacy: Any, job_dir: Path) -> dict[str, Any]:
    code = r'''
import inspect
import json
import traceback
from evidence_pack_engine import epistemic_authority as module
payload = {
    "schema": "dio.evidex.spine_preflight.v1",
    "module_file": str(getattr(module, "__file__", "")),
    "load_spine_source": inspect.getsource(module._load_spine),
}
try:
    spine = module._load_spine()
    payload.update({
        "state": "PASS",
        "spine_type": type(spine).__name__,
        "spine_module": type(spine).__module__,
    })
except Exception as exc:
    payload.update({
        "state": "REFUSE",
        "error_type": type(exc).__name__,
        "error": str(exc),
        "traceback": traceback.format_exc(),
    })
print(json.dumps(payload, ensure_ascii=True))
'''
    completed = subprocess.run(
        [str(legacy.EVIDEX_PYTHON), "-c", code],
        cwd=str(legacy.EVIDEX_ROOT),
        env=env,
        text=True,
        capture_output=True,
        check=False,
        timeout=60,
    )
    try:
        payload = json.loads(completed.stdout.strip().splitlines()[-1]) if completed.stdout.strip() else {}
    except json.JSONDecodeError:
        payload = {
            "schema": "dio.evidex.spine_preflight.v1",
            "state": "REFUSE",
            "error_type": "PreflightDecodeError",
            "error": completed.stderr.strip() or completed.stdout.strip(),
        }
    payload["returncode"] = completed.returncode
    payload["pythonpath"] = env.get("PYTHONPATH", "")
    payload["dio_root"] = env.get("DIO_ROOT")
    write_json(job_dir / "EVIDEX_DIO_SPINE_PREFLIGHT.json", payload)
    return payload


def _run_evidex_v2(job: dict[str, Any], out_root: Path) -> dict[str, Any]:
    from scripts import run_evidex_jobs as legacy

    job_dir = (out_root / "evidex" / job["job_id"]).resolve()
    engine_dir = job_dir / "evidex_engine"
    uploads_dir = engine_dir / "uploads"
    output_dir = engine_dir / "output"
    engine_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    intake = legacy.build_intake(job)
    intake_path = engine_dir / "intake.json"
    intake_path.write_text(json.dumps(intake, indent=2), encoding="utf-8")
    legacy.write_source_file(job, uploads_dir)

    env, roots = _spine_environment()
    env.update({"LLM_DISABLED": "1", "SUMMARY_USE_LLM": "0", "NARRATIVE_USE_LLM": "0"})
    preflight = _spine_preflight(env, legacy, job_dir)
    if preflight.get("state") != "PASS":
        diagnostic = str(preflight.get("traceback") or preflight.get("error") or "DIO epistemic spine preflight refused")
        receipt = {
            "job_id": job["job_id"],
            "created_at": legacy.utc_now(),
            "command": [],
            "returncode": 97,
            "stdout": "",
            "stderr": diagnostic,
            "intake_path": str(intake_path),
            "uploads_dir": str(uploads_dir),
            "output_dir": str(output_dir),
            "dio_spine_python_roots": [str(path) for path in roots],
            "dio_spine_preflight": preflight,
            "dio_spine_bypassed": False,
        }
        write_json(job_dir / "EVIDEX_RUN_RECEIPT.json", receipt)
        return receipt

    cmd = [
        str(legacy.EVIDEX_PYTHON),
        "-m",
        "evidence_pack_engine.cli",
        "generate",
        "--intake",
        str(intake_path),
        "--uploads",
        str(uploads_dir),
        "--out",
        str(output_dir),
    ]
    result = subprocess.run(
        cmd,
        cwd=str(legacy.EVIDEX_ROOT),
        env=env,
        text=True,
        capture_output=True,
        check=False,
    )
    receipt = {
        "job_id": job["job_id"],
        "created_at": legacy.utc_now(),
        "command": cmd,
        "returncode": result.returncode,
        "stdout": result.stdout.strip(),
        "stderr": result.stderr.strip(),
        "intake_path": str(intake_path),
        "uploads_dir": str(uploads_dir),
        "output_dir": str(output_dir),
        "dio_spine_python_roots": [str(path) for path in roots],
        "dio_spine_preflight": preflight,
        "dio_spine_bypassed": False,
    }
    write_json(job_dir / "EVIDEX_RUN_RECEIPT.json", receipt)
    return receipt


def install_red13_compat() -> None:
    """Install second-pass repairs before the prepared executor binds helpers."""
    from adapters.document_studio import pipeline as document_pipeline
    from products import professional_evidence_executor as executor
    from products import professional_evidence_final_compat as final_compat
    from scripts import run_evidex_jobs

    if getattr(executor, "_dio_red13_compat_installed", False):
        return

    # Sophia's generated integrity response may use anaphoric refusal wording.
    # Preserve the actual refusal requirement while avoiding one brittle phrase.
    final_compat._assignment_boundary_present = _assignment_boundary_present_v2

    # Keep VAMP's strict request schema closed. DIO lineage remains in the
    # surrounding binding receipt / projected source DB, never as an ad-hoc field.
    profile_review = executor._run_profile_review

    def vamp(packet: dict[str, Any], execution_dir: Path, *, incarnation: str, operator_id: str, now: str) -> dict[str, Any]:
        return _run_vamp_v2(
            packet,
            execution_dir,
            incarnation=incarnation,
            operator_id=operator_id,
            now=now,
            profile_review=profile_review,
        )

    executor._run_vamp_corrected = vamp

    # A source document's first paragraph is not automatically the cover title.
    # Retype a distinct Markdown heading/paragraph before Format Core rendering.
    original_builder = document_pipeline.build_paragraph_semantic_content

    def semantic_builder(*, object_id: str, version: str, title: str, source_language: str, source_rows: list[dict[str, str]], context: dict[str, Any], translations: dict[str, Any] | None = None, target_language: str | None = None, translation_status: str = "human_review_required") -> dict[str, Any]:
        content = original_builder(
            object_id=object_id,
            version=version,
            title=title,
            source_language=source_language,
            source_rows=source_rows,
            context=context,
            translations=translations,
            target_language=target_language,
            translation_status=translation_status,
        )
        return _repair_first_semantic_block(content, explicit_title=title)

    document_pipeline.build_paragraph_semantic_content = semantic_builder

    # Retain the anti-clone gate. Feed it compact semantic atoms instead of one
    # omnibus pain sentence that the legacy story realiser can repeat verbatim.
    executor._run_campaign_lab = _run_campaign_lab_v2

    # Direct Evidex and VAMP->Evidex now share the same DIO spine environment and
    # a preflight that exposes the concrete import failure if local code still differs.
    run_evidex_jobs.run_evidex = _run_evidex_v2

    executor._dio_red13_compat_installed = True


